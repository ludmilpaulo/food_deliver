export function homeT(locale: SupportedLocale, key: string): string | undefined {
  const table = homeTranslations[locale];
  if (table && key in table) {
    return table[key as HomeTranslationKey];
  }
  const en = homeTranslations.en;
  if (key in en) return en[key as HomeTranslationKey];
  return undefined;
}
