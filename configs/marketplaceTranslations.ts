export function marketplaceT(
  locale: SupportedLocale,
  key: string,
): string | undefined {
  const table = marketplaceTranslations[locale];
  if (table && key in table) {
    return table[key as MarketplaceTranslationKey];
  }
  const en = marketplaceTranslations.en;
  if (key in en) return en[key as MarketplaceTranslationKey];
  return undefined;
}
